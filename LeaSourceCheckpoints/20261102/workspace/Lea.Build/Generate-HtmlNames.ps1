$ErrorActionPreference='Stop'
$workspace=[IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$inputPath=Join-Path $workspace 'Lea.Engine/Data/entities.whatwg.json'
if((Get-FileHash -LiteralPath $inputPath).Hash -cne 'D741D877AC77C4194C4AD526B5B4A19AEF8DFE411AB840A466891CDBB9F362E6'){throw 'Pinned WHATWG entity table differs'}
$data=Get-Content -LiteralPath $inputPath -Raw|ConvertFrom-Json -AsHashtable
if($data.Count -ne 2231){throw 'Entity inventory differs'}
[string[]]$keys=@($data.Keys|ForEach-Object {$_.Substring(1)})
[Array]::Sort($keys,[StringComparer]::Ordinal)
$names=[Collections.Generic.List[string]]::new();$values=[Collections.Generic.List[string]]::new()
foreach($key in $keys){
    if($key -cnotmatch '^[A-Za-z][A-Za-z0-9]*;?$'){throw 'Unexpected entity name'}
    $entry=$data['&'+$key]
    $text='';foreach($point in $entry.codepoints){$text += [char]::ConvertFromUtf32($point)}
    if($text -cne $entry.characters -or $text.Contains([char]0)){throw 'Entity scalar mapping differs'}
    $names.Add($key)
    $encoded='';foreach($ch in $text.ToCharArray()){$encoded += '\u'+([int]$ch).ToString('X4')}
    $values.Add($encoded)
}
$lines=[Collections.Generic.List[string]]::new()
$lines.Add('// Generated by Lea.Build/Generate-HtmlNames.ps1 from https://html.spec.whatwg.org/entities.json')
$lines.Add('// Input SHA256 D741D877AC77C4194C4AD526B5B4A19AEF8DFE411AB840A466891CDBB9F362E6')
$lines.Add('namespace Lea.Engine { internal static partial class Hn {')
$lines.Add('    internal const int M = '+($keys|Measure-Object -Property Length -Maximum).Maximum+';')
foreach($pair in @(@('Keys',$names),@('Values',$values))){
    $lines.Add('    private static readonly string[] '+$pair[0]+' = (')
    for($i=0;$i -lt $pair[1].Count;$i+=64){
        $last=[Math]::Min($i+63,$pair[1].Count-1)
        $chunk=[string]::Join('\0',@($pair[1][$i..$last]))
        if($last -lt $pair[1].Count-1){$chunk+='\0'}
        $lines.Add('        "'+$chunk+'"'+$(if($last -lt $pair[1].Count-1){' +'}else{').Split(''\0'');'}))
    }
}
$lines.Add('} }')
[IO.File]::WriteAllLines((Join-Path $workspace 'Lea.Engine/Hn.Data.cs'),$lines,[Text.UTF8Encoding]::new($false))
$fixture=foreach($key in $keys){'&'+$key+"`t"+[Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($data['&'+$key].characters))}
[IO.File]::WriteAllLines((Join-Path $workspace 'Lea.Engine/Data/entities.expected.tsv'),$fixture,[Text.UTF8Encoding]::new($false))
Get-FileHash -LiteralPath (Join-Path $workspace 'Lea.Engine/Hn.Data.cs')
