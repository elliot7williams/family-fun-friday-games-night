using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Reflection.Metadata;
using System.Reflection.PortableExecutable;
using System.Security.Cryptography;
using System.Text.Json;

namespace Lea.Script.Tests
{
    internal static class Program
    {
        private static string resourceBase64;
        private static string[] resourceNames;
        private static string bootstrapKind;
        private static JsonElement optionsReport = JsonDocument.Parse("{}").RootElement.Clone();
        private static readonly List<object> rows = new List<object>();
        internal static void Check(bool condition, string name)
        {
            rows.Add(new { passed = condition, name });
            if (!condition) throw new InvalidOperationException("FAIL " + name);
        }
        private static int Main(string[] args)
        {
            string error = null;
            try
            {
                if (args.Length != 1) throw new ArgumentException("One pinned component required.");
                var path = Path.GetFullPath(args[0]);
                string hash;
                using (var file = File.OpenRead(path)) using (var sha = SHA256.Create()) hash = BitConverter.ToString(sha.ComputeHash(file)).Replace("-", "");
                if (hash != "F61B6858822F8F7BB0350B91D21862C6D22EC955EE94E2E4F4060FA01FB344F0") throw new InvalidDataException("Component differs.");
                using (var file = File.OpenRead(path)) using (var pe = new PEReader(file))
                {
                    var reader = pe.GetMetadataReader();
                    foreach (var handle in reader.TypeDefinitions)
                    {
                        var type = reader.GetTypeDefinition(handle);
                        if (reader.GetString(type.Name) != "<Module>") continue;
                        foreach (var method in type.GetMethods())
                            if (reader.GetString(reader.GetMethodDefinition(method).Name) == ".cctor") throw new InvalidOperationException("Unexpected module initializer.");
                    }
                }
                BootstrapEntry.Contract(path);
                BootstrapEntry.Checkpoints(path);
                var assembly = Assembly.LoadFrom(path);
                bootstrapKind = BootstrapEntry.Kind(path);
                resourceNames = assembly.GetManifestResourceNames();
                Check(resourceNames.SequenceEqual(new[] { "Lea.Script.Dom.js" }), "worker has only the compact bootstrap resource identity");
                using (var stream = assembly.GetManifestResourceStream("Lea.Script.Dom.js"))
                using (var output = new MemoryStream())
                {
                    if (stream == null) throw new InvalidDataException("Missing resource.");
                    stream.CopyTo(output);
                    var bytes = output.ToArray();
                    Check(Convert.ToHexString(SHA256.HashData(bytes)) == "196BCE962F2C2F375C77644D0AE19485820F599170D4D80013829A6ECD2886E3", "worker bootstrap resource retains the pinned generated bytes");
                    resourceBase64 = Convert.ToBase64String(bytes);
                }
                var previousOutput = Console.Out;
                using (var output = new StringWriter())
                {
                    int code;
                    try { Console.SetOut(output); code = OptionsUnit.Execute(new[] { path }); }
                    finally { Console.SetOut(previousOutput); }
                    if (code != 0) throw new InvalidOperationException("Compiled options unit failed.");
                    using (var document = JsonDocument.Parse(output.ToString())) optionsReport = document.RootElement.Clone();
                    Check(optionsReport.GetProperty("passed").GetBoolean() && optionsReport.GetProperty("rows").GetArrayLength() == 2,
                        "compiled worker options preserve original configuration, freshness and rejection checks at both budgets");
                }
                if (rows.Count != 14) throw new InvalidOperationException("Original bootstrap contract coverage differs.");
            }
            catch (Exception failure) { error = failure.ToString(); }
            Console.WriteLine(JsonSerializer.Serialize(new { passed = error == null, error, checks = rows,
                componentSha256 = "F61B6858822F8F7BB0350B91D21862C6D22EC955EE94E2E4F4060FA01FB344F0",
                sourceSuiteSha256 = "E09D86773BA03C5B2A8D32174D719695E481F7B3418CE1ACC83FAE63FE75A12C",
                resourceBase64, resourceNames, bootstrapKind, options = optionsReport, componentOnly = true, typedBootstrapContractChecksInvoked = true, workerEntryPointExecuted = false,
                pageCodeEvaluated = false, nativeIsolationTest = false }));
            return error == null ? 0 : 1;
        }
    }
}
